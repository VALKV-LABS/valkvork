#!/usr/bin/env bash
# Local development cluster: one controller and one agent on this machine,
# driving the local Docker Engine. State lives in .dev/ (gitignored).
#
#   scripts/dev.sh up | down | status | env | logs | reset
#
# TLS is on, with a throwaway CA, so the setup matches production. Containers
# the agent starts are ordinary Docker containers labelled valkvork.*.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEV="$ROOT/.dev"
BIN="${VALKVORK_BIN:-$ROOT/target/debug}"
ADMIN_PORT="${VALKVORK_DEV_ADMIN_PORT:-50052}"
AGENT_PORT="${VALKVORK_DEV_AGENT_PORT:-50051}"
METRICS_PORT="${VALKVORK_DEV_METRICS_PORT:-9400}"
AGENT_METRICS_PORT="${VALKVORK_DEV_AGENT_METRICS_PORT:-9401}"

log() { printf '\033[1m==>\033[0m %s\n' "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

docker_socket() {
  # Respect DOCKER_HOST, then the active context (Colima, Docker Desktop, OrbStack …).
  local host="${DOCKER_HOST:-}"
  [ -n "$host" ] || host="$(docker context inspect --format '{{.Endpoints.docker.Host}}' 2>/dev/null || true)"
  case "$host" in
    unix://*) echo "${host#unix://}" ;;
    "") echo /var/run/docker.sock ;;
    *) die "DOCKER_HOST=$host is not a unix socket; the agent needs a local socket" ;;
  esac
}

running() { [ -f "$DEV/$1.pid" ] && kill -0 "$(cat "$DEV/$1.pid")" 2>/dev/null; }

listening() { (exec 3<>"/dev/tcp/127.0.0.1/$1") 2>/dev/null; }

setup() {
  command -v openssl >/dev/null || die "openssl is required"
  command -v docker >/dev/null || die "docker is required"
  docker info >/dev/null 2>&1 || die "Docker is not running"
  mkdir -p "$DEV/tls" "$DEV/db" "$DEV/data"

  if [ ! -f "$DEV/tls/server.pem" ]; then
    log "Creating a throwaway CA and a localhost certificate in .dev/tls"
    (
      cd "$DEV/tls"
      openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes \
        -keyout ca.key -out ca.pem -days 365 -subj "/CN=valkvork-dev-ca" 2>/dev/null
      openssl req -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes \
        -keyout server.sec1.key -out server.csr -subj "/CN=localhost" 2>/dev/null
      printf 'subjectAltName=DNS:localhost,IP:127.0.0.1\nbasicConstraints=CA:FALSE\nkeyUsage=digitalSignature\nextendedKeyUsage=serverAuth\n' > ext.cnf
      openssl x509 -req -in server.csr -CA ca.pem -CAkey ca.key -CAcreateserial \
        -out server.pem -days 365 -extfile ext.cnf 2>/dev/null
      openssl pkcs8 -topk8 -nocrypt -in server.sec1.key -out server.key
      rm -f server.sec1.key server.csr ext.cnf ca.srl
    )
  fi
  [ -f "$DEV/join-token" ] || openssl rand -hex 24 > "$DEV/join-token"
  [ -f "$DEV/admin-token" ] || openssl rand -hex 32 > "$DEV/admin-token"
  chmod 600 "$DEV/join-token" "$DEV/admin-token" "$DEV/tls/"*.key

  cat > "$DEV/controller.toml" <<EOF
# Generated by scripts/dev.sh
agent_listen_addr   = "127.0.0.1:$AGENT_PORT"
admin_listen_addr   = "127.0.0.1:$ADMIN_PORT"
metrics_listen_addr = "127.0.0.1:$METRICS_PORT"
tls_cert_file       = "$DEV/tls/server.pem"
tls_key_file        = "$DEV/tls/server.key"
database_path       = "$DEV/db/valkvork.db"
join_token_file     = "$DEV/join-token"
admin_token_file    = "$DEV/admin-token"
# Short grace period so a restarted dev controller settles quickly.
recovery_grace_period_seconds = 5
EOF

  # The data dir must be visible to the Docker daemon for the /alloc bind
  # mounts; Colima and Docker Desktop share the home directory.
  cat > "$DEV/agent.toml" <<EOF
# Generated by scripts/dev.sh
controller_endpoint = "https://localhost:$AGENT_PORT"
ca_file             = "$DEV/tls/ca.pem"
join_token_file     = "$DEV/join-token"
node_class          = "general"
data_dir            = "$DEV/data"
docker_socket       = "$(docker_socket)"
registry_auth_file  = "$DEV/registry-auth.json"
metrics_listen_addr = "127.0.0.1:$AGENT_METRICS_PORT"

[reserved]
cpu    = 0.5
memory = "512MiB"
EOF
}

env_lines() {
  cat <<EOF
export VALKVORK_ADDR=https://localhost:$ADMIN_PORT
export VALKVORK_CA_FILE=$DEV/tls/ca.pem
export VALKVORK_ADMIN_TOKEN=$(cat "$DEV/admin-token")
EOF
}

up() {
  [ -x "$BIN/valkvork-controller" ] || die "binaries missing in $BIN; run 'make build' first"
  setup
  for port in "$ADMIN_PORT" "$AGENT_PORT" "$METRICS_PORT" "$AGENT_METRICS_PORT"; do
    if listening "$port" && ! running controller && ! running agent; then
      die "port $port is already in use (override with VALKVORK_DEV_*_PORT)"
    fi
  done

  if running controller; then
    log "Controller already running (pid $(cat "$DEV/controller.pid"))"
  else
    log "Starting valkvork-controller (log: .dev/controller.log)"
    RUST_LOG="${RUST_LOG:-info}" nohup "$BIN/valkvork-controller" --config "$DEV/controller.toml" \
      >> "$DEV/controller.log" 2>&1 < /dev/null &
    echo $! > "$DEV/controller.pid"
    for _ in $(seq 50); do listening "$ADMIN_PORT" && break; sleep 0.2; done
    listening "$ADMIN_PORT" || { tail -20 "$DEV/controller.log" >&2; die "controller did not start"; }
  fi

  if running agent; then
    log "Agent already running (pid $(cat "$DEV/agent.pid"))"
  else
    log "Starting valkvork-agent against $(docker_socket) (log: .dev/agent.log)"
    local since=0
    [ -f "$DEV/agent.log" ] && since=$(wc -l < "$DEV/agent.log")
    RUST_LOG="${RUST_LOG:-info}" nohup "$BIN/valkvork-agent" --config "$DEV/agent.toml" \
      >> "$DEV/agent.log" 2>&1 < /dev/null &
    echo $! > "$DEV/agent.pid"
    for _ in $(seq 50); do
      tail -n +"$((since + 1))" "$DEV/agent.log" 2>/dev/null | grep -q 'registered with controller' && break
      running agent || { tail -20 "$DEV/agent.log" >&2; die "agent exited"; }
      sleep 0.2
    done
  fi

  status
  cat <<EOF

Web UI:  https://localhost:$ADMIN_PORT/ui/
         The certificate comes from .dev/tls/ca.pem, so the browser warns once;
         accept it, or trust that CA. Sign in with the admin token:
           $(cat "$DEV/admin-token")

CLI:     eval "\$(make -s env)"   # then: valkvork status, valkvork apply -f examples/web.toml
Metrics: http://127.0.0.1:$METRICS_PORT/metrics (controller), http://127.0.0.1:$AGENT_METRICS_PORT/metrics (agent)
Stop:    make dev-down        Wipe state and containers: make dev-reset
EOF
}

stop_one() {
  if running "$1"; then
    log "Stopping $1"
    kill "$(cat "$DEV/$1.pid")"
    for _ in $(seq 50); do running "$1" || break; sleep 0.1; done
  fi
  rm -f "$DEV/$1.pid"
}

down() {
  # The agent goes first; containers keep running, as they would in production.
  stop_one agent
  stop_one controller
  local n
  n=$(dev_containers | wc -l | tr -d ' ')
  [ "$n" = 0 ] || [ "${1:-}" = quiet ] || log "$n Valkvork container(s) left running; 'make dev-up' re-adopts them, 'make dev-reset' removes them"
}

status() {
  for p in controller agent; do
    if running "$p"; then printf '  %-11s running (pid %s)\n' "$p" "$(cat "$DEV/$p.pid")"; else printf '  %-11s stopped\n' "$p"; fi
  done
  if running controller && [ -x "$BIN/valkvork" ]; then
    eval "$(env_lines)"
    echo
    "$BIN/valkvork" node list || true
    echo
    "$BIN/valkvork" status 2>/dev/null | tail -n +3 || true
  fi
}

# Containers this dev agent created: labelled, with /alloc under .dev/data.
# Valkvork containers from any other cluster on this Docker are left alone.
dev_containers() {
  local id
  for id in $(docker ps -aq --filter label=valkvork.workload_id 2>/dev/null); do
    docker inspect --format '{{range .Mounts}}{{.Source}} {{end}}' "$id" 2>/dev/null \
      | grep -q "$DEV/data/" && echo "$id"
  done
  return 0
}

reset() {
  local ids
  ids=$(dev_containers)
  down quiet
  if [ -n "$ids" ]; then
    log "Removing Valkvork containers: $(echo "$ids" | wc -l | tr -d ' ')"
    # shellcheck disable=SC2086
    docker rm -f $ids >/dev/null
  fi
  log "Deleting .dev/"
  rm -rf "$DEV"
}

case "${1:-}" in
  up) up ;;
  down) down ;;
  status) status ;;
  env) [ -f "$DEV/admin-token" ] || die "no dev cluster yet; run 'make dev-up'"; env_lines ;;
  logs) touch "$DEV/controller.log" "$DEV/agent.log"; tail -n 50 -F "$DEV/controller.log" "$DEV/agent.log" ;;
  reset) reset ;;
  *) die "usage: $0 up|down|status|env|logs|reset" ;;
esac
